#!/usr/bin/env node
/**
 * Builds src/lib/username-model.ts, the letter-trigram table behind
 * looksRandomUsername() in src/lib/username-randomness.ts.
 *
 *   node scripts/build-username-model.mjs <zxcvbn-data-dir>
 *
 * <zxcvbn-data-dir> holds the frequency lists that ship with zxcvbn (MIT):
 * english_wikipedia.txt, female_names.txt, male_names.txt, surnames.txt and
 * us_tv_and_film.txt, one lowercase word per line. On top of those it adds
 * pinyin, romanised Japanese and Korean syllables, so names like "xiaozhu",
 * "lunahikaru" or "kimtaehyung" read as names rather than as noise.
 *
 * Each table entry is the log-likelihood ratio, in nats, of the next letter
 * under this model versus under a uniformly random letter. A word scores
 * well above zero over its length; a string of random letters scores well
 * below it. The values are quantised to one character each.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/build-username-model.mjs <zxcvbn-data-dir>");
  process.exit(1);
}

const words = [];
for (const f of ["english_wikipedia", "female_names", "male_names", "surnames", "us_tv_and_film"]) {
  for (const line of readFileSync(join(dir, `${f}.txt`), "utf8").split("\n")) {
    const w = line.trim().toLowerCase();
    if (/^[a-z]+$/.test(w)) words.push(w);
  }
}

const initials = ["", "b", "p", "m", "f", "d", "t", "n", "l", "g", "k", "h", "j", "q", "x", "zh", "ch", "sh", "r", "z", "c", "s", "y", "w"];
const finals = ["a", "o", "e", "i", "u", "ai", "ei", "ao", "ou", "an", "en", "ang", "eng", "ong", "ia", "ie", "iao", "iu", "ian", "in", "iang", "ing", "iong", "ua", "uo", "uai", "ui", "uan", "un", "uang", "ue", "er"];
const pinyin = initials.flatMap((i) => finals.map((f) => i + f));
const romaji = ["", "k", "s", "t", "n", "h", "m", "y", "r", "w", "g", "z", "d", "b", "p", "sh", "ch", "ts", "j"]
  .flatMap((c) => [..."aiueo"].map((v) => c + v))
  .concat(["n"]);
const korean = ["kim", "lee", "park", "choi", "jung", "kang", "cho", "yoon", "jang", "lim", "han", "oh", "seo", "shin", "kwon", "hwang", "ahn", "song", "yoo", "hong", "jeon", "ko", "moon", "yang", "son", "bae", "baek", "heo", "nam", "tae", "hyung", "hyun", "min", "jin", "woo", "seung", "young", "eun", "ji", "soo", "joon", "hee", "sung", "kyung", "jae", "dong", "gyu", "yeon", "hye"];

// Deterministic PRNG so the table is reproducible.
let seed = 7;
const rand = () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const pick = (a) => a[Math.floor(rand() * a.length)];
const join2 = (a, lo, hi) => {
  const n = lo + Math.floor(rand() * (hi - lo + 1));
  let s = "";
  for (let i = 0; i < n; i++) s += pick(a);
  return s;
};
// Syllables strung together, so transitions across syllables are learned too.
for (let i = 0; i < 4000; i++) {
  words.push(join2(pinyin, 2, 3));
  words.push(join2(romaji, 2, 4));
}
for (let i = 0; i < 5; i++) words.push(...korean);

// Alphabet: "^" (start), a-z, "$" (end). Contexts are two symbols from "^a-z".
const CTX = "^abcdefghijklmnopqrstuvwxyz";
const OUT = "abcdefghijklmnopqrstuvwxyz$";
const uni = new Map(), bi = new Map(), tri = new Map(), bictx = new Map(), trictx = new Map();
const inc = (m, k) => m.set(k, (m.get(k) ?? 0) + 1);
let total = 0;
for (const w of words) {
  const s = "^^" + w + "$";
  for (let i = 2; i < s.length; i++) {
    const c = s[i];
    inc(uni, c);
    total++;
    inc(bi, s[i - 1] + c);
    inc(bictx, s[i - 1]);
    inc(tri, s.slice(i - 2, i) + c);
    inc(trictx, s.slice(i - 2, i));
  }
}
const pUni = (c) => ((uni.get(c) ?? 0) + 1) / (total + OUT.length);
const p = (h, c) => {
  const pb = bictx.get(h[1]) ? (bi.get(h[1] + c) ?? 0) / bictx.get(h[1]) : pUni(c);
  const pt = trictx.get(h) ? (tri.get(h + c) ?? 0) / trictx.get(h) : pUni(c);
  return 0.1 * pUni(c) + 0.3 * pb + 0.6 * pt;
};

// A random letter is 1/26; a username ends after ~8 letters, so "$" is 1/8.
const base = (c) => (c === "$" ? Math.log(1 / 8) : Math.log(1 / 26));
const STEP = 0.25, MIN = -12.75; // 64 levels: [-12.75, 3.0]
const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
let table = "";
for (const a of CTX) for (const b of CTX) {
  // "x^" never occurs as a context: "^" only appears as a prefix.
  for (const c of OUT) {
    const v = Math.log(p(a + b, c)) - base(c);
    const q = Math.max(0, Math.min(63, Math.round((v - MIN) / STEP)));
    table += ALPHABET[q];
  }
}

const out = `// Generated by scripts/build-username-model.mjs. Do not edit by hand.
// Letter-trigram log-likelihood ratios (model vs uniform random letters),
// quantised to one base64 character each: value = index * ${STEP} + (${MIN}).
// Index order: context1 (${CTX.length}) x context2 (${CTX.length}) x next (${OUT.length}).
export const MODEL_CONTEXT = ${JSON.stringify(CTX)};
export const MODEL_OUTCOME = ${JSON.stringify(OUT)};
export const MODEL_STEP = ${STEP};
export const MODEL_MIN = ${MIN};
export const MODEL_TABLE =
${table.match(/.{1,96}/g).map((l) => `  ${JSON.stringify(l)}`).join(" +\n")};
`;
writeFileSync(new URL("../src/lib/username-model.ts", import.meta.url), out);
console.log(`wrote ${table.length} entries from ${words.length} words`);
